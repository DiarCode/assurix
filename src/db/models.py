class Finding(Base):
    __tablename__ = "findings"

    id: Mapped[str] = mapped_column(String(36), primary_key=True, default=lambda: str(uuid.uuid4()))
    engagement_id: Mapped[str] = mapped_column(ForeignKey("engagements.id"), nullable=False)
    title: Mapped[str] = mapped_column(String(500), nullable=False)
    description: Mapped[str] = mapped_column(Text, nullable=False)
    severity: Mapped[Severity] = mapped_column(String(20), nullable=False)
    confidence_score: Mapped[float] = mapped_column(Float, default=0.0)
    validated: Mapped[bool] = mapped_column(Boolean, default=False)
    cwe_id: Mapped[str | None] = mapped_column(String(20), nullable=True)
    owasp_category: Mapped[str | None] = mapped_column(String(50), nullable=True)
    remediation: Mapped[str | None] = mapped_column(Text, nullable=True)
    source_agent: Mapped[str] = mapped_column(String(100), nullable=False)
    finding_metadata: Mapped[dict] = mapped_column(JSON, default=dict)
    # Stable identity used for deduplication at report time. Nullable
    # so legacy findings (pre-dedup-aware pipeline) can remain valid;
    # NULL rows are skipped by ``_deduplicate_findings()``.
    dedup_key: Mapped[str | None] = mapped_column(String(64), nullable=True, index=True)
    # --- v2 Verifier Triad (plan §3.2.3) ----------------------------------
    # Each finding's triadic verdict is captured as a *run id* pointing
    # at the ``verifier_runs`` row that recorded the vote. All three
    # must be non-null for a finding to reach ``validated=True`` (the
    # ``strict_finding_gate`` enforces this in the validator pipeline).
    reproducer_run_id: Mapped[str | None] = mapped_column(String(36), nullable=True)
    adversary_run_id: Mapped[str | None] = mapped_column(String(36), nullable=True)
    validator_run_id: Mapped[str | None] = mapped_column(String(36), nullable=True)
    # SHA-256 of the canonical evidence blob. Set once and never
    # mutated; downstream chains key off this hash.
    evidence_hash: Mapped[str | None] = mapped_column(String(64), nullable=True)
    # Set True only after Validator clears scope + dedup. Drives
    # ExploitChainer's BFS in §5.4 — only chain_eligible findings
    # participate.
    chain_eligible: Mapped[bool] = mapped_column(Boolean, default=False, server_default=text("0"))
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), default=lambda: datetime.now(UTC)
    )

    engagement: Mapped[Engagement] = relationship("Engagement", back_populates="findings")
    artifacts: Mapped[list["EvidenceArtifact"]] = relationship(
        "EvidenceArtifact", back_populates="finding"
    )
    provenance_links: Mapped[list["ProvenanceLink"]] = relationship("ProvenanceLink", back_populates="finding")


