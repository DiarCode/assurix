    # reasoner writes this at the end of its run; the GET
    # /scans/{id}/chains endpoint reads from here. Keeping the
    # chains as a first-class column (rather than nesting them
    # inside the JSON ``config`` blob) makes the persistence
    # explicit and the read path a single ``session.refresh`` —
    # no LLM call, no graph rebuild on read.
    chains: Mapped[list] = mapped_column(JSON, default=list)
    chain_run_at: Mapped[datetime | None] = mapped_column(
        DateTime(timezone=True), nullable=True
    )
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), default=lambda: datetime.now(UTC)
    )

    target: Mapped[Target] = relationship("Target", back_populates="engagements")
    findings: Mapped[list["Finding"]] = relationship("Finding", back_populates="engagement")
    jobs: Mapped[list["Job"]] = relationship("Job", back_populates="engagement")
    artifacts: Mapped[list["EvidenceArtifact"]] = relationship(
        "EvidenceArtifact", back_populates="engagement"
    )
    audit_logs: Mapped[list["AuditLog"]] = relationship("AuditLog", back_populates="engagement")
    hypotheses: Mapped[list["Hypothesis"]] = relationship("Hypothesis", back_populates="engagement")
