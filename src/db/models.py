class HypothesisStatus(StrEnum):
    """Status of a hypothesis during the research loop (8-state, plan §3.1.1).

    The 4-state enum from v1 (PENDING/INVESTIGATING/CONFIRMED/FALSIFIED) is
    replaced by the 8-state lifecycle from src/reasoning/state_machine.py.
    A destructive alembic migration (alembic/versions/2026-07-01_assurix_v2_
    architecture.py) backs this change with a 4->8 value remap.

    Mappings for the destructive migration (4 -> 8):
        PENDING            -> CANDIDATE
        INVESTIGATING      -> NEEDS_CORROBORATION
        CONFIRMED          -> VALIDATED
        FALSIFIED          -> REJECTED

    Per plan §3.1.1 (BL-5): a fall-back to the 2-state pattern (CANDIDATE
    -> VALIDATED in one step) is FORBIDDEN and is asserted-illegal by the
    HypothesisStateMachine.transit() call.
    """
    UNKNOWN = "unknown"
    CANDIDATE = "candidate"
    NEEDS_CORROBORATION = "needs_corroboration"
    NEEDS_SAFE_VALIDATION = "needs_safe_validation"
    VALIDATED = "validated"
    REJECTED = "rejected"
    OUT_OF_SCOPE = "out_of_scope"
    SUPERSEDED = "superseded"


class Hypothesis(Base):
    """A hypothesis class generated by the ResearchLoop for investigation.

    Hypotheses are the core unit of work in the Mythos architecture.
    Each hypothesis represents a class of vulnerabilities to investigate,
    generated from pattern matching (VulnerabilityPatternLibrary) or LLM creativity.
    """
    __tablename__ = "hypotheses"

    id: Mapped[str] = mapped_column(String(36), primary_key=True, default=lambda: str(uuid.uuid4()))
    engagement_id: Mapped[str] = mapped_column(ForeignKey("engagements.id"), nullable=False)
    hypothesis_class: Mapped[str] = mapped_column(String(100), nullable=False, index=True)
    source: Mapped[HypothesisSource] = mapped_column(String(20), nullable=False)
    description: Mapped[str] = mapped_column(Text, nullable=False)
    confidence: Mapped[float] = mapped_column(Float, default=0.5)
    status: Mapped[HypothesisStatus] = mapped_column(String(20), default=HypothesisStatus.UNKNOWN)
    attack_category: Mapped[str] = mapped_column(String(100), nullable=False)
    # Parent hypothesis for refinement lineage (null = top-level)
    parent_hypothesis_id: Mapped[str | None] = mapped_column(ForeignKey("hypotheses.id"), nullable=True)
    # Capability tags needed to investigate this hypothesis (e.g., ["xss", "injection"])
    required_capabilities: Mapped[list] = mapped_column(JSON, default=list)
    # What constitutes falsification for this hypothesis
    falsification_criteria: Mapped[str] = mapped_column(Text, nullable=True)
    # Plan §3.1.1 (BL-5): the full transition chain as a JSON array of
    # {from_state, to_state, evidence_hash, timestamp, reason} objects.
    # The HypothesisStateMachine.transit() call appends to this list and
    # raises IllegalTransition for any non-allowed transition.
    state_transitions: Mapped[list] = mapped_column(JSON, default=list)
    # Content-addressed sha256 of the evidence blob backing the most recent
    # transition. Immutable: the evidence_blobs table stores the actual
    # request/response, this column is the lookup key.
    evidence_hash: Mapped[str | None] = mapped_column(String(64), nullable=True)
    # Plan §3.1.1: confidence is decayed on each transition. The current
    # value reflects the cumulative effect of all transitions to date.
    confidence_decay: Mapped[float] = mapped_column(Float, default=0.5)
    # Timestamp of the most recent state transition (for query/sort).
    last_transition_at: Mapped[datetime | None] = mapped_column(
        DateTime(timezone=True), nullable=True
    )
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), default=lambda: datetime.now(UTC)
    )
    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), default=lambda: datetime.now(UTC), onupdate=lambda: datetime.now(UTC)
    )

    # Relationships (string annotations for forward references)
    engagement: Mapped["Engagement"] = relationship("Engagement", back_populates="hypotheses")
    parent_hypothesis: Mapped["Hypothesis | None"] = relationship("Hypothesis", remote_side=[id])
    provenance_links: Mapped[list["ProvenanceLink"]] = relationship("ProvenanceLink", back_populates="hypothesis")
    tool_invocations: Mapped[list["ToolInvocation"]] = relationship("ToolInvocation", back_populates="hypothesis")


class ToolInvocation(Base):
    """Records each tool invocation within the research loop.

    Links a hypothesis to the specific tool that was used to investigate it,
    enabling end-to-end provenance from finding to hypothesis to tool."""
    __tablename__ = "tool_invocations"

    id: Mapped[str] = mapped_column(String(36), primary_key=True, default=lambda: str(uuid.uuid4()))
    engagement_id: Mapped[str] = mapped_column(ForeignKey("engagements.id"), nullable=False)
    hypothesis_id: Mapped[str] = mapped_column(ForeignKey("hypotheses.id"), nullable=False)
    tool_name: Mapped[str] = mapped_column(String(100), nullable=False)
    # Capability tags used to select this tool (e.g., ["xss", "injection"])
    capability_tags: Mapped[list] = mapped_column(JSON, default=list)
    target: Mapped[str] = mapped_column(Text, nullable=False)
    params: Mapped[dict] = mapped_column(JSON, default=dict)
    result_summary: Mapped[dict | None] = mapped_column(JSON, nullable=True)
    started_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), default=lambda: datetime.now(UTC))
    completed_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True), nullable=True)
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), default=lambda: datetime.now(UTC)
    )

    # Relationships (string annotations for forward references)
    engagement: Mapped["Engagement"] = relationship("Engagement", back_populates="tool_invocations")
    hypothesis: Mapped["Hypothesis"] = relationship("Hypothesis", back_populates="tool_invocations")
    provenance_links: Mapped[list["ProvenanceLink"]] = relationship("ProvenanceLink", back_populates="tool_invocation")


class ProvenanceLink(Base):
    """Links a finding to its hypothesis, tool invocation, and tool.

    Enables end-to-end provenance tracing: finding -> hypothesis -> tool invocation -> tool.
    Required for the Mythos evidence bar: every confirmed finding must have a complete chain.

    Note (Phase 2): hypothesis_id and tool_invocation_id are now nullable so that
    standard-pipeline findings (no hypothesis context) can still carry provenance
    via the tool_name field. When both are null, tool_name holds the agent name
    (e.g. "pentester").
    """
    __tablename__ = "provenance_links"

    id: Mapped[str] = mapped_column(String(36), primary_key=True, default=lambda: str(uuid.uuid4()))
    finding_id: Mapped[str] = mapped_column(ForeignKey("findings.id"), nullable=False)
    # Nullable: standard pipeline findings have no hypothesis context.
    hypothesis_id: Mapped[str | None] = mapped_column(
        ForeignKey("hypotheses.id"), nullable=True
    )
    # Nullable: standard pipeline findings have no tool invocation record.
    tool_invocation_id: Mapped[str | None] = mapped_column(
        ForeignKey("tool_invocations.id"), nullable=True
    )
    tool_name: Mapped[str] = mapped_column(String(100), nullable=False)
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), default=lambda: datetime.now(UTC)
    )

    # Relationships (string annotations for forward references)
    finding: Mapped["Finding"] = relationship("Finding", back_populates="provenance_links")
    hypothesis: Mapped["Hypothesis"] = relationship("Hypothesis", back_populates="provenance_links")
    tool_invocation: Mapped["ToolInvocation"] = relationship("ToolInvocation", back_populates="provenance_links")

    # Composite index for efficient chain queries
    __table_args__ = (
        Index("ix_provenance_chain", "finding_id", "hypothesis_id", "tool_invocation_id"),
    )


